import random

# Два списка с приятными словами
first_words = ["ты", "у тебя", "в тебе", "твой", "твоя"]
second_words = ["замечательный", "потрясающая", "волшебный", "прекрасный", "невероятно крутая"]

def generate_compliment():
    word1 = random.choice(first_words)
    word2 = random.choice(second_words)
    # Простая подстройка под род: если второе слово явно женское, добавляем «ты» или «твоя»
    if word2 in ["потрясающая", "прекрасный"]:
        # Для простоты делаем универсально через «ты такой/такая», но тут оставим базовый вариант
        return f"{word1} {word2}!"
    return f"{word1} {word2}!"

# Пример: сгенерируем 5 комплиментов
for _ in range(5):
    print(generate_compliment())
#    Что тут происходит (в твоём стиле — по шагам random.choice(...) берёт случайный элемент из списка — это как range и цикл, только для выбора одного значения.
#    Функция generate_compliment() собирает фразу: первое слово из первого списка, второе — из второго.
#    Цикл for _ in range(5) выводит 5 разных комплиментов подряд.
#    Примеры того, что может получиться
#    ты замечательный!
#   у тебя потрясающий!
#    в тебе волшебный!
#    твой прекрасный!
#    твоя невероятно крутая!
